export type SystemMessageKey = keyof typeof faSystemCatalog;
export type SystemMessageParams = Record<string, string | number>;

export function translateSystem(locale: Locale, key: SystemMessageKey, params?: SystemMessageParams) {
  let message: string = locale === "en" ? key : faSystemCatalog[key];
  if (!params) return message;
  for (const [name, value] of Object.entries(params)) message = message.replaceAll(`{${name}}`, String(value));
  return message;
}
