const catalogs: Record<Locale, Record<BusinessMessageKey, string>> = {
  "fa-IR": faBusinessCatalog,
  en: enBusinessCatalog,
};

export function translateBusiness(locale: Locale, key: BusinessMessageKey, params?: BusinessMessageParams) {
  const template = catalogs[locale][key] ?? faBusinessCatalog[key];
  if (!params) return template;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, token: string) => {
    const value = params[token];
    return value === undefined ? match : String(value);
  });
}
